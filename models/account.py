"""Core abstract account model for LogicBank.

This module defines the shared behaviour for every bank account type.
Concrete account classes inherit from :class:`BankAccount` and implement
their own withdrawal policy.
"""

from abc import ABC, abstractmethod
from decimal import Decimal
from typing import Any

from exceptions import (
    AccountError,
    InsufficientFundsError,
    MinimumBalanceError,
)
from models.customer import Customer
from models.transaction import Transaction, TransactionType
from utils.validators import to_money, validate_non_empty


class BankAccount(ABC):
    """Abstract base class that stores an owner's account and its activity.

    The account balance and transaction collection are encapsulated. Callers
    can read the balance and obtain an immutable snapshot of transaction
    history, but cannot replace the internal collections directly.

    Args:
        owner: Customer who owns the account.
        account_number: Unique account identifier generated by the bank service.
        opening_balance: Initial balance. Zero is allowed.

    Raises:
        AccountError: If ``owner`` is not a Customer instance.
        ValidationError: If the account number is empty.
        InvalidAmountError: If the opening balance is invalid.
    """

    def __init__(
        self,
        owner: Customer,
        account_number: str,
        opening_balance: Decimal = Decimal("0.00"),
    ) -> None:
        if not isinstance(owner, Customer):
            raise AccountError("A valid customer is required.")

        self.owner = owner
        self.account_number = validate_non_empty(
            account_number, "Account number"
        )

        # Keep the monetary value as Decimal to avoid binary float errors.
        self.__balance = to_money(opening_balance, allow_zero=True)
        self.__transactions: list[Transaction] = []

    @property
    def balance(self) -> Decimal:
        """Return the current account balance without exposing its setter."""
        return self.__balance

    @property
    def transactions(self) -> tuple[Transaction, ...]:
        """Return an immutable snapshot of the account's transaction history."""
        return tuple(self.__transactions)

    def get_balance(self) -> Decimal:
        """Return the current balance.

        This method is retained as an explicit method-based alternative to
        reading the ``balance`` property.
        """
        return self.__balance

    def deposit(self, amount: Decimal) -> Transaction:
        """Deposit a positive amount and record the successful transaction.

        Args:
            amount: Amount to deposit. Float values are rejected by
                ``to_money`` to protect monetary precision.

        Returns:
            The transaction created for this deposit.
        """
        amount = to_money(amount)

        self.__balance += amount

        transaction = Transaction(
            transaction_type=TransactionType.DEPOSIT,
            amount=amount,
            description=f"Deposit into {self.account_number}",
        )

        self.__transactions.append(transaction)
        return transaction

    @abstractmethod
    def withdraw(self, amount: Decimal) -> Transaction:
        """Withdraw money according to the concrete account's rules.

        Subclasses must implement this method. For example, a savings account
        protects a minimum balance while a current account may permit an
        explicitly configured overdraft.
        """
        raise NotImplementedError

    def _complete_withdrawal(
        self,
        amount: Decimal,
        minimum_balance: Decimal,
    ) -> Transaction:
        """Apply a withdrawal after enforcing the supplied balance floor.

        This protected helper centralizes the balance update and transaction
        creation so subclasses only need to supply their withdrawal limit.

        ``minimum_balance`` may be negative for a current account with an
        overdraft facility. The public account constructors validate the
        configured limits before this helper is called.
        """
        amount = to_money(amount)

        minimum_balance = Decimal(str(minimum_balance)).quantize(
            Decimal("0.01")
        )

        if not minimum_balance.is_finite():
            raise AccountError("Invalid account withdrawal limit.")

        if self.__balance - amount < minimum_balance:
            if minimum_balance > 0:
                raise MinimumBalanceError(
                    "Withdrawal would violate the minimum balance."
                )

            raise InsufficientFundsError(
                "Insufficient account balance."
            )

        self.__balance -= amount

        transaction = Transaction(
            transaction_type=TransactionType.WITHDRAWAL,
            amount=amount,
            description=f"Withdrawal from {self.account_number}",
        )

        self.__transactions.append(transaction)
        return transaction

    def _get_account_summary(self) -> dict[str, Any]:
        """Return the basic account details used by presentation code."""
        return {
            "owner": self.owner.full_name,
            "account_number": self.account_number,
            "account_type": self.__class__.__name__,
            "balance": self.__balance,
        }
